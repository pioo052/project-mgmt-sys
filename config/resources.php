$projectScope = static function (array $user, string $role, string $alias): array {
    if ($role === 'student') {
        return ["$alias.student_id IN (SELECT id FROM students WHERE user_id = ?)", [(int) $user['id']]];
    }
    if ($role === 'supervisor') {
        return ["$alias.supervisor_id = ?", [(int) $user['id']]];
    }
    return ['1 = 1', []];
};
$proposalScope = static function (array $user, string $role, string $alias): array {
    if ($role === 'student') {
        return ["$alias.submitted_by = ?", [(int) $user['id']]];
    }
    if ($role === 'supervisor') {
        return ["$alias.supervisor_id = ?", [(int) $user['id']]];
    }
    return ['1 = 1', []];
};
$projectChildScope = static function (array $user, string $role, string $alias): array {
    if ($role === 'student') {
        return ["$alias.project_id IN (SELECT id FROM research_projects WHERE student_id IN (SELECT id FROM students WHERE user_id = ?))", [(int) $user['id']]];
    }
    if ($role === 'supervisor') {
        return ["$alias.project_id IN (SELECT id FROM research_projects WHERE supervisor_id = ?)", [(int) $user['id']]];
    }
    return ['1 = 1', []];
};

